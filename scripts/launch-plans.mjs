import fs from "node:fs";
import ts from "typescript";

const source = fs.readFileSync("src/lib/launch-plans.ts", "utf8");
const js = ts.transpileModule(source, {
  compilerOptions: { module: ts.ModuleKind.ESNext },
}).outputText;
const { LAUNCH_PLANS, STANDARD_DELIVERY_TIME } = await import(
  `data:text/javascript;base64,${Buffer.from(js).toString("base64")}`
);
const sql = `-- Generated by node scripts/launch-plans.mjs. Do not edit values here.
begin;
create or replace function public.launch_plan(p_plan text)
returns jsonb language sql immutable set search_path = public as $fn$
  select coalesce('${JSON.stringify(LAUNCH_PLANS)}'::jsonb -> p_plan,
    '${JSON.stringify(LAUNCH_PLANS.uno)}'::jsonb);
$fn$;
create or replace function public.standard_delivery_time()
returns time language sql immutable as $fn$ select '${STANDARD_DELIVERY_TIME}'::time; $fn$;
create or replace function public.plan_topic_cap(p_plan text)
returns integer language sql immutable as $fn$ select (public.launch_plan(p_plan)->>'topics')::integer; $fn$;
create or replace function public.plan_priority_source_cap(p_plan text)
returns integer language sql immutable as $fn$ select (public.launch_plan(p_plan)->>'prioritySources')::integer; $fn$;
create or replace function public.plan_history_days(p_plan public.plan_tier)
returns integer language sql immutable as $fn$ select (public.launch_plan(p_plan::text)->>'retentionDays')::integer; $fn$;
create or replace function public.plan_alert_days(p_plan public.plan_tier)
returns integer language sql immutable as $fn$ select public.plan_history_days(p_plan); $fn$;
commit;
`;
const path = "supabase/migrations/0081_launch_plan_values.sql";
if (process.argv.includes("--check")) {
  if (fs.readFileSync(path, "utf8") !== sql)
    throw new Error("Launch SQL is stale. Run node scripts/launch-plans.mjs");
} else fs.writeFileSync(path, sql);

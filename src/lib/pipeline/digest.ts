/**
 * Stage 7 — building a briefing, then sending it.
 *
 * ---------------------------------------------------------------------------
 * Deterministic assembly, not a per-reader model call (docs/track.md phase 2)
 * ---------------------------------------------------------------------------
 *
 * Stages 3 and 4 understood an event once, for everybody. Stage 5 decided who
 * sees it, with no model. This stage used to write one short paragraph per
 * person per story; it now assembles `digest_items.why_it_matters` from
 * `event_impacts` — the shared explanation written once per event, either
 * during analysis (the common case, `analyse.ts`) or backfilled lazily here
 * the first time a digest needs an event analysed before this existed. No
 * model call scales with reader count any more. A reader who wants something
 * written for them specifically has Story Ask — "why does this matter to
 * me?" — which is the explicit, on-demand, metered path for that, not this
 * one.
 *
 * An event whose shared impact is still being generated by another worker,
 * or has permanently failed, is left out of *this* digest rather than
 * blocking it — `briefed_at` stays unset, so it is picked up by this
 * reader's next scheduled digest once (or if) the impact completes. That is
 * the same "store, don't force" philosophy the pre-analysis demand gate
 * uses: nothing is lost, delivery is just deferred.
 *
 * A quiet day is a real outcome: `status = 'skipped'`, zero items, and a short
 * email that says so rather than a padded briefing. Paused readers are not
 * scheduled at all.
 *
 * ---------------------------------------------------------------------------
 * Idempotence
 * ---------------------------------------------------------------------------
 *
 * `(user_id, scheduled_for)` is unique, so creating the next slot twice writes
 * nothing the second time. An event already in a digest_item for this reader
 * is never selected again. A delivery is unique on `(digest_id, channel)`, and
 * the Resend call carries the same pair as an idempotency key, so a retry of a
 * send whose response was lost does not land twice in the inbox. Impact
 * generation has its own claim, shaped exactly like `analyse.ts`'s event
 * claim, so two workers racing to backfill the same event pay for it once.
 */


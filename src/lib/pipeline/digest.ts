export type MatchRow = {
  eventId: string;
  relevance: number;
  matchedAt: string;
};

/**
 * Highest relevance first, events already briefed dropped, capped at density.
 *
 * Exported because this is the decision a quiet day hangs on, and it must be
 * the same decision in a test as in a run.
 *
 * A relevance of exactly 0 is dropped whatever the cap still has room for. By
 * `relevanceOf` in match.ts that score is an importance-0 event with no novelty,
 * one matching topic and no priority source — nothing on any axis the matcher
 * measures. Even Deep, the band that admits "everything with a plausible claim
 * on your attention", is admitting a claim; zero is the absence of one. Carrying
 * it produces a paragraph in which the model tells the reader the story does not
 * affect them, which is a worse briefing than one three stories shorter.
 */
export function selectItems(matches: MatchRow[], already: Set<string>, cap: number): MatchRow[] {
  return matches
    .filter((row) => row.relevance > 0 && !already.has(row.eventId))
    .sort((a, b) => b.relevance - a.relevance || Date.parse(b.matchedAt) - Date.parse(a.matchedAt))
    .slice(0, Math.max(0, cap));
}

export type WhyItem = { eventId: string; why: string };

/**
 * The model's reply, turned into one paragraph per requested event — or null.
 *
 * Missing an event, or returning an empty paragraph for one, is a refused
 * reply rather than a patched one. A digest that silently dropped a story the
 * matcher admitted is a briefing the reader cannot trust, and a paragraph
 * invented here to fill the gap would be the one lie this product exists not
 * to tell.
 */
export function readWhys(reply: unknown, eventIds: string[]): WhyItem[] | null {
  if (typeof reply !== "object" || reply === null || Array.isArray(reply)) return null;
  const raw = (reply as Record<string, unknown>)["items"];
  if (!Array.isArray(raw)) return null;

  const byId = new Map<string, string>();
  for (const entry of raw) {
    if (typeof entry !== "object" || entry === null || Array.isArray(entry)) continue;
    const row = entry as Record<string, unknown>;
    const eventId = typeof row["event_id"] === "string" ? row["event_id"].trim() : "";
    const why = typeof row["why_it_matters"] === "string" ? row["why_it_matters"].trim() : "";
    if (eventId === "" || why === "") continue;
    if (!byId.has(eventId)) byId.set(eventId, why);
  }

  const items: WhyItem[] = [];
  for (const id of eventIds) {
    const why = byId.get(id);
    if (why === undefined) return null;
    items.push({ eventId: id, why });
  }
  return items;
}

export async function digest(db: Db, options: DigestOptions = {}): Promise<DigestReport> {
  const started = options.now ?? new Date();
  const startedAt = started.toISOString();
  const outcomes: DigestOutcome[] = [];

  const scheduled = await scheduleUpcoming(db, started, options);

  const due = await loadDue(db, started, options);
  let generated = 0;
  let skipped = 0;
  let failed = 0;
  let paused = 0;
  let deferred = 0;
  let tokens = 0;

  for (const row of due) {
    const outcome = await generateOne(db, row, options);
    outcomes.push(outcome);
    tokens += outcome.tokens;
    if (outcome.decision === "generated") generated += 1;
    else if (outcome.decision === "skipped") skipped += 1;
    else if (outcome.decision === "failed") failed += 1;
    else if (outcome.decision === "paused") paused += 1;
    else if (outcome.decision === "deferred") deferred += 1;
  }

  let sent = 0;
  let retried = 0;
  if (options.skipSend !== true && options.dryRun !== true) {
    const delivery = await deliverDue(db, options);
    sent = delivery.sent;
    retried = delivery.retried;
    for (const outcome of outcomes) {
      const match = delivery.byDigest.get(outcome.digestId ?? "");
      if (match) outcome.sent = match;
    }
  }

  return {
    startedAt,
    finishedAt: new Date().toISOString(),
    scheduled,
    generated,
    skipped,
    failed,
    paused,
    deferred,
    sent,
    retried,
    tokens,
    outcomes,
  };
}

type PrefRow = {
  user_id: string;
  send_at: string;
  timezone: string;
  days: number[];
  channels: DeliveryChannel[];
  frequency: DigestFrequency;
  density: number;
  paused: boolean;
  instructions: string;
  language: string;
};

const PREF_COLUMNS =
  "user_id, send_at, timezone, days, channels, frequency, density, paused, instructions, language";

async function scheduleUpcoming(db: Db, now: Date, options: DigestOptions): Promise<number> {
  let query = db.from("notification_preferences").select(PREF_COLUMNS);
  if (options.userIds) query = query.in("user_id", options.userIds);

  const { data, error } = await query;
  if (error) throw new Error(`reading notification_preferences: ${error.message}`);

  const rows = (data ?? []) as PrefRow[];
  const scheduled: { user_id: string; scheduled_for: string; status: "scheduled" }[] = [];

  for (const row of rows) {
    if (row.paused) continue;
    const slot = options.immediate
      ? now
      : nextSlot(
          {
            sendAt: row.send_at,
            timezone: row.timezone,
            days: row.days,
            frequency: row.frequency,
          },
          now,
        );
    if (slot === null) continue;
    scheduled.push({
      user_id: row.user_id,
      scheduled_for: slot.toISOString(),
      status: "scheduled",
    });
  }

  if (options.dryRun !== true && scheduled.length > 0) {
    const { error: writeError } = await db.from("digests").upsert(scheduled, {
      onConflict: "user_id,scheduled_for",
      ignoreDuplicates: true,
    });
    if (writeError) throw new Error(`scheduling digest: ${writeError.message}`);
  }

  return scheduled.length;
}

type DueRow = {
  digest_id: string;
  user_id: string;
  scheduled_for: string;
  status: DigestStatus;
  generation_deferred_until: string | null;
};

async function loadDue(db: Db, now: Date, options: DigestOptions): Promise<DueRow[]> {
  const stale = new Date(now.getTime() - STALE_MINUTES * 60_000).toISOString();
  let query = db
    .from("digests")
    .select("digest_id, user_id, scheduled_for, status, generation_deferred_until")
    .lte("scheduled_for", now.toISOString())
    .or(`status.eq.scheduled,and(status.eq.generating,generated_at.is.null)`)
    .or(`generation_deferred_until.is.null,generation_deferred_until.lte.${now.toISOString()}`)
    .order("scheduled_for", { ascending: true })
    .limit(options.limit ?? BATCH);

  if (options.userIds) query = query.in("user_id", options.userIds);

  const { data, error } = await query;
  if (error) throw new Error(`reading due digests: ${error.message}`);

  return ((data ?? []) as DueRow[]).filter((row) => {
    if (row.status === "scheduled") return true;
    // generating with no generated_at is a crashed claim; honour STALE_MINUTES
    // via scheduled_for being in the past is not enough — we only reclaim if
    // the row is old enough that a live worker cannot still hold it. The
    // filter above cannot express last_updated, so we compare scheduled_for
    // against stale as a floor: a digest that became due more than fifteen
    // minutes ago and is still generating is abandoned.
    return row.status === "generating" && row.scheduled_for < stale;
  });
}

type EventBrief = {
  eventId: string;
  title: string;
  whatHappened: string;
  /**
   * Carried so the translation `content_version` hashed at generation time
   * matches the one hashed at delivery time. Both sides must hash exactly
   * the same fields, or every lookup is a permanent cache miss that looks
   * identical to a cold cache.
   */
  beforeState: string | null;
  afterState: string | null;
  importance: number;
  novelty: number;
  topics: string[];
  relevance: number;
  matchedAt: string;
};

async function generateOne(db: Db, due: DueRow, options: DigestOptions): Promise<DigestOutcome> {
  const base = {
    userId: due.user_id,
    digestId: due.digest_id,
    scheduledFor: due.scheduled_for,
    items: 0,
    tokens: 0,
    sent: 0,
  };

  const prefs = await loadPref(db, due.user_id);
  if (prefs === null) {
    return { ...base, decision: "failed", detail: "no preferences row" };
  }

  if (prefs.paused) {
    if (options.dryRun !== true) {
      await finish(db, due.digest_id, "skipped", 0, 0);
    }
    return { ...base, decision: "paused", detail: "briefings paused" };
  }

  const claimed = await claimDigest(db, due, options);
  if (claimed !== "held") {
    return { ...base, decision: "held", detail: claimed };
  }

  const plan = await planFor(db, due.user_id);
  const cap = capFor(prefs.density, plan);
  const matches = await loadMatches(db, due.user_id);
  const already = await alreadyBriefed(db, due.user_id);
  const picked = selectItems(matches, already, cap);

  // The digest cache (0061) is deliberately not consulted. Skipping generation on
  // an unchanged event set is a P1 optimization; the table and RPCs stay dormant
  // in the database so it can be switched back on after P0.

  if (picked.length === 0) {
    if (options.dryRun !== true) {
      await finish(db, due.digest_id, "skipped", 0, 0);
      await queueDeliveries(db, due.digest_id, due.user_id, prefs.channels);
    }
    return { ...base, decision: "skipped", detail: "nothing matched since the last briefing" };
  }

  const briefs = await loadBriefs(db, picked);

  let ready: ImpactResult[];
  let tokens: number;
  try {
    const resolved = await resolveImpacts(db, briefs, options);
    ready = resolved.ready;
    tokens = resolved.tokens;
  } catch (error) {
    const floor = error instanceof TruncatedCompletionError ? error.reasoningTokens : 0;
    const retryAt = aiCapacityRetryAt(error, options.now ?? new Date());
    if (options.dryRun !== true) {
      if (retryAt !== null) await deferDigest(db, due.digest_id, retryAt);
      else await finish(db, due.digest_id, "failed", 0, floor);
    }
    return {
      ...base,
      tokens: floor,
      decision: retryAt === null ? "failed" : "deferred",
      detail:
        retryAt === null
          ? `model: ${error instanceof Error ? error.message : String(error)}`
          : `temporary AI capacity; retry after ${retryAt.toISOString()}`,
    };
  }

  if (ready.length === 0) {
    // Every picked story's shared explanation is still being written elsewhere,
    // or permanently failed. Nothing is lost: briefed_at stays unset below, so
    // these events are picked up again by this reader's next scheduled digest.
    if (options.dryRun !== true) {
      await finish(db, due.digest_id, "skipped", 0, tokens);
      await queueDeliveries(db, due.digest_id, due.user_id, prefs.channels);
    }
    return {
      ...base,
      tokens,
      decision: "skipped",
      detail: "no story's shared explanation is ready yet",
    };
  }

  if (options.dryRun === true) {
    return {
      ...base,
      items: ready.length,
      tokens,
      decision: "generated",
      detail: `${ready.length} stories (dry run)`,
    };
  }

  // Prewarm the reader's language for exactly the stories going into this
  // briefing — the small set plan2 §45 permits, not the corpus. Shared and
  // cached, so a second reader of the same language pays nothing. English
  // returns immediately without a round trip.
  const language = toLanguageTag(prefs.language);
  if (needsTranslation(language)) {
    const { data: translationFlag } = await db
      .from("feature_flags")
      .select("enabled")
      .eq("key", "story_translation_enabled")
      .maybeSingle();

    if (translationFlag?.enabled === true) {
      const byId = new Map(ready.map((r) => [r.eventId, r.text]));
      const translated = await translateEvents(
        db,
        briefs
          .filter((b) => byId.has(b.eventId))
          .map((b) => translatable(b, byId.get(b.eventId) ?? null)),
        language,
        {
          ...(options.secrets ? { secrets: options.secrets } : {}),
          now: options.now ?? new Date(),
        },
      );
      tokens += translated.tokens;
    }
  }

  const rows = ready.map((item, position) => ({
    digest_id: due.digest_id,
    event_id: item.eventId,
    position,
    why_it_matters: item.text,
  }));

  const { error } = await db
    .from("digest_items")
    .upsert(rows, { onConflict: "digest_id,event_id" });
  if (error) {
    await finish(db, due.digest_id, "failed", 0, tokens);
    return { ...base, tokens, decision: "failed", detail: `writing items: ${error.message}` };
  }

  await db
    .from("user_events")
    .update({ briefed_at: new Date().toISOString() })
    .eq("user_id", due.user_id)
    .in(
      "event_id",
      ready.map((item) => item.eventId),
    );

  await finish(db, due.digest_id, "ready", ready.length, tokens);
  await queueDeliveries(db, due.digest_id, due.user_id, prefs.channels);

  return {
    ...base,
    items: ready.length,
    tokens,
    decision: "generated",
    detail: `${ready.length} stories`,
  };
}

/**
 * The exact shape a translation is keyed on, built one way.
 *
 * Generation and delivery both go through this. They must, because
 * `content_version` is a hash of these fields: if the two callsites built the
 * object differently — a null where the other had text — every lookup would
 * miss, translations would regenerate on every send, and the symptom would be
 * indistinguishable from a cache that was simply cold.
 */
function translatable(
  event: {
    eventId: string;
    title: string;
    whatHappened: string;
    beforeState: string | null;
    afterState: string | null;
  },
  impact: string | null,
): TranslatableEvent {
  return {
    eventId: event.eventId,
    title: event.title,
    whatHappened: event.whatHappened,
    beforeState: event.beforeState,
    afterState: event.afterState,
    impact,
  };
}

export type ImpactResult = { eventId: string; text: string };

type ImpactRow = {
  event_id: string;
  status: ImpactStatus;
  text: string | null;
  updated_at: string;
  deferred_until: string | null;
};

/**
 * Deterministic where possible: reads the shared impact already written by
 * analysis. Falls back to generating it — once, shared, claimed the same way
 * `analyse.ts` claims an event — only for events analysed before 0028
 * existed. That backlog only shrinks: every event analysed from here on
 * writes its impact as part of the same call that understands it.
 *
 * Events another worker is writing (`generating`, at any age) or has
 * permanently failed to write are simply absent from the result — see the
 * module doc for why that is the correct behaviour rather than a bug. An aged
 * `generating` row is NOT treated as free to retake: a claim that has gone
 * quiet is not proof that the paid call behind it never happened.
 */
async function resolveImpacts(
  db: Db,
  briefs: EventBrief[],
  options: DigestOptions,
): Promise<{ ready: ImpactResult[]; tokens: number }> {
  const ids = briefs.map((b) => b.eventId);
  const existing = await loadImpacts(db, ids);
  const now = options.now ?? new Date();

  const ready: ImpactResult[] = [];
  const needsBackfill: EventBrief[] = [];

  for (const brief of briefs) {
    const row = existing.get(brief.eventId);
    if (row?.status === "complete" && row.text) {
      ready.push({ eventId: brief.eventId, text: row.text });
    } else if (row === undefined || (row.status === "pending" && isDue(row.deferred_until, now))) {
      needsBackfill.push(brief);
    }
    // 'generating' (held elsewhere, however old) or 'failed': left out this
    // round. Matches `claimImpacts`, which only ever takes a due 'pending' row —
    // selecting anything else here would only produce claims that always lose.
  }

  if (needsBackfill.length === 0 || options.dryRun === true) {
    return { ready, tokens: 0 };
  }

  let tokens = 0;
  for (let offset = 0; offset < needsBackfill.length; offset += WHY_CHUNK_SIZE) {
    const chunk = needsBackfill.slice(offset, offset + WHY_CHUNK_SIZE);
    const claimed = await claimImpacts(db, chunk, now);
    if (claimed.length === 0) continue;

    let result;
    try {
      result = await completeRoutedJson<unknown>({
        capability: "digest",
        system: `${IMPACT_PROMPT}\n\n${impactContract()}`,
        user: renderImpactBrief(claimed),
        maxTokens: 8192,
        feature: "impact",
        ...(options.secrets ? { secrets: options.secrets } : {}),
      });
    } catch (error) {
      const retryAt = aiCapacityRetryAt(error, now);
      if (retryAt !== null) await deferImpacts(db, claimed, retryAt);
      throw error;
    }
    const { data, usage } = result;
    tokens += usage.promptTokens + usage.completionTokens;

    const parsed = readWhys(
      data,
      claimed.map((b) => b.eventId),
    );
    if (parsed === null) {
      await failImpacts(db, claimed, usage.completionTokens);
      continue;
    }
    await completeImpacts(db, parsed, usage);
    for (const item of parsed) ready.push({ eventId: item.eventId, text: item.why });
  }

  return { ready, tokens };
}

async function loadImpacts(db: Db, eventIds: string[]): Promise<Map<string, ImpactRow>> {
  if (eventIds.length === 0) return new Map();
  const { data, error } = await db
    .from("event_impacts")
    .select("event_id, status, text, updated_at, deferred_until")
    .in("event_id", eventIds);
  if (error) throw new Error(`reading event_impacts: ${error.message}`);
  return new Map((data ?? []).map((row) => [row.event_id, row]));
}

function isDue(deferredUntil: string | null, now: Date): boolean {
  return deferredUntil === null || Date.parse(deferredUntil) <= now.getTime();
}

/**
 * Claims a batch of events for impact generation, the same shape as
 * `analyse.ts`'s `claimEvent`: ensure a row exists, then a conditional
 * update decides the winner atomically so two workers backfilling the same
 * event cannot both pay for it. Only a due `pending` row is ever taken:
 * `failed` is not reclaimed (see the module doc), and neither is `generating`,
 * at any age — a stale claim is recovered by an operator, never by the cron
 * buying the same explanation twice.
 */
async function claimImpacts(db: Db, briefs: EventBrief[], now: Date): Promise<EventBrief[]> {
  const ids = briefs.map((b) => b.eventId);

  const { error: seedError } = await db.from("event_impacts").upsert(
    ids.map((event_id) => ({ event_id, status: "pending" as const })),
    { onConflict: "event_id", ignoreDuplicates: true },
  );
  if (seedError) throw new Error(`seeding event_impacts: ${seedError.message}`);

  const { data, error } = await db
    .from("event_impacts")
    .update({ status: "generating", deferred_until: null, updated_at: now.toISOString() })
    .in("event_id", ids)
    .eq("status", "pending")
    .or("deferred_until.is.null,deferred_until.lte." + now.toISOString())
    .select("event_id");
  if (error) throw new Error(`claiming event_impacts: ${error.message}`);

  const won = new Set((data ?? []).map((row) => row.event_id));
  return briefs.filter((b) => won.has(b.eventId));
}

async function completeImpacts(
  db: Db,
  items: WhyItem[],
  usage: { promptTokens: number; completionTokens: number },
): Promise<void> {
  const each = Math.max(1, items.length);
  const rows = items.map((item) => ({
    event_id: item.eventId,
    status: "complete" as const,
    deferred_until: null,
    text: item.why,
    prompt_tokens: Math.round(usage.promptTokens / each),
    completion_tokens: Math.round(usage.completionTokens / each),
    updated_at: new Date().toISOString(),
  }));
  const { error } = await db.from("event_impacts").upsert(rows, { onConflict: "event_id" });
  if (error) throw new Error(`writing event_impacts: ${error.message}`);
}

/**
 * Records a failed backfill attempt and what it cost — the same
 * money-ledger reasoning as `analyse.ts`'s `recordFailure`. Not retried by
 * the schedule; a permanently unwritable impact means that one story stays
 * out of every future digest for every reader until an operator retries it
 * by name, which is the same bounded-failure trade this project has made
 * everywhere else a shared cost can fail.
 */
async function failImpacts(db: Db, briefs: EventBrief[], completionTokens: number): Promise<void> {
  const each = Math.max(1, briefs.length);
  const rows = briefs.map((b) => ({
    event_id: b.eventId,
    status: "failed" as const,
    deferred_until: null,
    completion_tokens: Math.round(completionTokens / each),
    updated_at: new Date().toISOString(),
  }));
  const { error } = await db.from("event_impacts").upsert(rows, { onConflict: "event_id" });
  if (error) throw new Error(`marking event_impacts failed: ${error.message}`);
}

async function deferImpacts(db: Db, briefs: EventBrief[], retryAt: Date): Promise<void> {
  const { error } = await db
    .from("event_impacts")
    .update({
      status: "pending",
      deferred_until: retryAt.toISOString(),
      updated_at: new Date().toISOString(),
    })
    .in(
      "event_id",
      briefs.map((brief) => brief.eventId),
    );
  if (error) throw new Error(`deferring event_impacts: ${error.message}`);
}

function renderImpactBrief(briefs: EventBrief[]): string {
  const lines = ["Stories, each shown to every reader it is briefed to:"];
  for (const brief of briefs) {
    lines.push(
      `- event_id ${brief.eventId}`,
      `  title: ${brief.title}`,
      `  what happened: ${brief.whatHappened || "(not analysed)"}`,
      `  topics: ${brief.topics.join(", ") || "(none)"}`,
      `  importance ${brief.importance.toFixed(1)}, novelty ${brief.novelty.toFixed(1)}`,
    );
  }
  return lines.join("\n");
}

async function claimDigest(db: Db, due: DueRow, options: DigestOptions): Promise<"held" | string> {
  if (options.dryRun === true) return "held";

  const { data, error } = await db
    .from("digests")
    .update({ status: "generating" })
    .eq("digest_id", due.digest_id)
    .in("status", ["scheduled", "generating"])
    .select("digest_id");

  if (error) return `claiming: ${error.message}`;
  if ((data?.length ?? 0) === 0) return "already claimed";
  return "held";
}


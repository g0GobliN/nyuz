/** Four readers leave room for their database and delivery subrequests on Workers Free. */
const BATCH = 4;

/** How long a `generating` claim is honoured before another run may take it. */
const STALE_MINUTES = 15;

/** Send attempts before a queued delivery is marked failed for good. */
const MAX_ATTEMPTS = 5;

/**
 * How long to wait after each failed attempt, indexed by attempt number.
 *
 * The retryable errors are the ones where the far side is asking for less
 * traffic — a Resend or Telegram 429, a push service 503. Retrying every reader
 * on the next five-minute tick answers being rate limited with a synchronised
 * burst against whoever just rate limited us, and burns all five attempts
 * inside twenty-five minutes, so a half-hour outage failed the entire batch
 * permanently.
 *
 * These four delays stretch the same five attempts across roughly eighty
 * minutes, which is long enough to sit out a typical provider incident, while
 * the jitter below spreads a batch that failed together across the window
 * rather than re-converging on it.
 */
const RETRY_BACKOFF_MINUTES = [2, 6, 18, 54];

/**
 * When a delivery that has just failed its `attempts`th try may be tried again.
 *
 * The ±25% jitter is the point of the function, not a detail: without it every
 * delivery queued in the same cron run shares a deadline and the herd stays a
 * herd for all five attempts.
 */
export function nextAttemptAt(attempts: number, now: number = Date.now()): string {
  const index = Math.min(Math.max(attempts, 1), RETRY_BACKOFF_MINUTES.length) - 1;
  const minutes = RETRY_BACKOFF_MINUTES[index] ?? RETRY_BACKOFF_MINUTES[0] ?? 2;
  const jittered = minutes * (0.75 + Math.random() * 0.5);
  return new Date(now + jittered * 60_000).toISOString();
}

/** A bounded reply prevents one truncation from losing a 30- or 50-story briefing. */
export const WHY_CHUNK_SIZE = 10;

/**
 * The shared-impact prompt. Written for whoever ends up reading it, not for
 * one person — this text is generated once per event and reused by every
 * reader it is briefed to (docs/track.md phase 2). The per-reader version of
 * this ("why does this matter to *me*") is Story Ask, on explicit request.
 */
const IMPACT_PROMPT = `You write one short, sharp explanation of why a news event matters, for a reader who tracks this space — not personalised to one person. This text is shown to everyone this story is briefed to.

Be concrete. Name the constraint that shifted, the decision this forces, the thing that no longer works the old way. Prefer "the caching model for server components just changed" over "this is relevant to web developers".

Never restate the headline. Never hedge. Never invent a consequence the coverage does not support.`;

function impactContract(): string {
  return `Reply with JSON only, in exactly this shape:

{
  "items": [
    { "event_id": "uuid", "why_it_matters": "one or two sentences" }
  ]
}

Return one item for every event you were given, using the event_id exactly as supplied. why_it_matters is one or two sentences, never a headline restated.`;
}

export type DigestOptions = {
  userIds?: string[] | undefined;
  /** Generate the current slot immediately, even if send_at is still ahead. */
  now?: Date | undefined;
  /** Decide and report, write nothing. Still calls the model. */
  dryRun?: boolean | undefined;
  /** Digests to generate this run. Absent means `BATCH`. */
  limit?: number | undefined;
  secrets?: SecretBag | undefined;
  email?: EmailEnv | undefined;
  telegram?: TelegramEnv | undefined;
  push?: PushEnv | undefined;
  /** Skip sending after generating. */
  skipSend?: boolean | undefined;
  /**
   * Create a slot due right now for `--user`, instead of waiting for send_at.
   * For checking a known reader, not for the cron.
   */
  immediate?: boolean | undefined;
};

